import {readFileSync,writeFileSync} from 'node:fs';
import {openapi} from '../src/contracts.js';

// Deliberately retain unknown JSON where the wire schema has no field contract.
function type(schema={}) {
  if(schema.$ref)return 'Schemas['+JSON.stringify(schema.$ref.split('/').at(-1))+']';
  if(schema.const!==undefined)return JSON.stringify(schema.const);
  if(schema.enum)return schema.enum.map(value=>JSON.stringify(value)).join(' | ');
  if(schema.oneOf||schema.anyOf)return (schema.oneOf??schema.anyOf).map(type).join(' | ');
  if(schema.allOf)return schema.allOf.map(type).join(' & ');
  if(Array.isArray(schema.type))return schema.type.map(value=>type({...schema,type:value})).join(' | ');
  if(schema.type==='null')return 'null';
  if(schema.type==='string')return 'string';
  if(schema.type==='integer'||schema.type==='number')return 'number';
  if(schema.type==='boolean')return 'boolean';
  if(schema.type==='array')return 'Array<'+type(schema.items)+'>';
  if(schema.type==='object'||schema.properties){
    const fields=Object.entries(schema.properties??{}).map(([name,value])=>JSON.stringify(name)+(schema.required?.includes(name)?'':'?')+': '+type(value)+';');
    for(const name of schema.required??[])if(!Object.hasOwn(schema.properties??{},name))fields.push(JSON.stringify(name)+': unknown;');
    const additional=schema.additionalProperties;
    if(additional!==false)fields.push('[key: string]: '+(additional&&typeof additional==='object'?type(additional):'unknown')+';');
    return '{ '+fields.join(' ')+' }';
  }
  return 'unknown';
}
let output='// Generated by tools/generate-wire-types.mjs from src/contracts.js.\n';
output+='export interface Schemas {\n'+Object.entries(openapi.components.schemas).map(([name,schema])=>'  '+JSON.stringify(name)+': '+type(schema)+';').join('\n')+'\n}\n';
output+='export interface Operations {\n';
for(const [path,item]of Object.entries(openapi.paths))for(const [method,operation]of Object.entries(item)){
  const request=operation.requestBody?.content?.['application/json']?.schema;
  const response=Object.entries(operation.responses).find(([status])=>Number(status)>=200&&Number(status)<300)?.[1].content?.['application/json']?.schema;
  const parameters=[...path.matchAll(/\{([^}]+)\}/g)].map(match=>JSON.stringify(match[1])+': string;').join(' ');
  output+='  '+JSON.stringify(operation.operationId)+': { request: '+(request?type(request):'undefined')+'; response: '+type(response)+'; path: { '+parameters+' }; method: '+JSON.stringify(method.toUpperCase())+' };\n';
}
output+='}\n';
const target=new URL('../src/wire-types.d.ts',import.meta.url);
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==output)throw new Error('Generated wire types are stale');}
else writeFileSync(target,output);
